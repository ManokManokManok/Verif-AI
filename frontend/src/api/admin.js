/**
 * Export analysis statistics as CSV or Excel-compatible CSV.
 * @param {Object} params - Query parameters
 * @param {string} params.startDate - Start date
 * @param {string} params.endDate - End date
 * @param {string} params.period - Period grouping
 * @param {string} params.format - csv|excel
 * @param {number} params.limit - Number of top categories to include
 * @returns {Promise<{blob: Blob, filename: string}>}
 */
export async function exportAnalysisStats({
  startDate,
  endDate,
  period,
  format = 'csv',
  limit = 10,
  fallbackData,
  fallbackMeta,
  preferClientExport = false,
} = {}) {
  const params = new URLSearchParams();
  if (startDate) params.append('start_date', startDate);
  if (endDate) params.append('end_date', endDate);
  if (period) params.append('period', period);
  if (format) params.append('format', format);
  if (limit) params.append('limit', limit.toString());

  const queryString = params.toString();
  const url = `${API_BASE}/admin/analysis-stats/export/${queryString ? `?${queryString}` : ''}`;

  const headers = {};
  const accessToken = window.localStorage.getItem('access_token');
  if (accessToken) {
    headers.Authorization = `Bearer ${accessToken}`;
  }

  const localStats = fallbackData?.stats;
  const localCategories = fallbackData?.categories;
  const localMeta = fallbackMeta || {};

  if (preferClientExport && localStats) {
    const csvContent = buildAnalysisStatsCsv(localStats || {}, Array.isArray(localCategories) ? localCategories : [], localMeta);
    const blobType = format === 'excel' ? 'application/vnd.ms-excel' : 'text/csv';
    const extension = format === 'excel' ? 'xls' : 'csv';
    const safePeriod = period || 'all_time';
    const filename = `analysis_stats_${safePeriod}_${new Date().toISOString().slice(0, 10).replace(/-/g, '')}.${extension}`;
    return {
      blob: new Blob([csvContent], { type: blobType }),
      filename,
    };
  }

  const response = await fetch(url, {
    method: 'GET',
    headers,
  });

  if (!response.ok) {
    if (response.status === 404) {
      let statsForExport = localStats;
      let categoriesForExport = Array.isArray(localCategories) ? localCategories : [];

      if (!statsForExport) {
        const [statsRes, categoriesRes] = await Promise.all([
          getAnalysisStats({ startDate, endDate, period }),
          getTopScamCategories({ startDate, endDate, period, limit }),
        ]);

        if (!statsRes?.success) {
          throw new Error('Failed to load analysis stats for export fallback');
        }

        statsForExport = statsRes.data || {};
        categoriesForExport = categoriesRes?.success ? (categoriesRes.data || []) : [];
      }

      const csvContent = buildAnalysisStatsCsv(statsForExport || {}, categoriesForExport, localMeta);
      const blobType = format === 'excel' ? 'application/vnd.ms-excel' : 'text/csv';
      const extension = format === 'excel' ? 'xls' : 'csv';
      const safePeriod = period || 'all_time';
      const filename = `analysis_stats_${safePeriod}_${new Date().toISOString().slice(0, 10).replace(/-/g, '')}.${extension}`;
      return {
        blob: new Blob([csvContent], { type: blobType }),
        filename,
      };
    }

    let message = `Failed to export analysis statistics (${response.status})`;
    try {
      const errorData = await response.json();
      message = errorData?.error?.message || errorData?.message || message;
    } catch {
      // Ignore non-JSON errors
    }
    const error = new Error(message);
    error.status = response.status;
    throw error;
  }

  const blob = await response.blob();
  const contentDisposition = response.headers.get('content-disposition') || '';
  const filenameMatch = contentDisposition.match(/filename="?([^";]+)"?/i);
  const filename = filenameMatch?.[1] || `analysis_stats_export.${format === 'excel' ? 'xls' : 'csv'}`;

  return { blob, filename };
}

