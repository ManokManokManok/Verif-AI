const API_BASE =
  import.meta.env.VITE_API_BASE_URL?.replace(/\/$/, '') ||
  'http://localhost:8000/api';

function buildAnalysisStatsCsv(stats = {}, categories = [], metadata = {}) {
  const rows = [];

  const formatDateTime = (value) => {
    if (!value) return 'N/A';
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return String(value);
    return date.toISOString().replace('T', ' ').replace('Z', ' UTC').split('.')[0];
  };

  const formatDateOnly = (value) => {
    if (!value) return '';
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return String(value).slice(0, 10);
    return date.toISOString().slice(0, 10);
  };

  const totalCount = stats.total_count || 0;
  const previousTotalCount = stats.previous_total_count || 0;
  const scamCount = stats.scam_count || 0;
  const previousScamCount = stats.previous_scam_count || 0;
  const highRiskCount = stats.high_risk_count || 0;
  const mediumRiskCount = stats.medium_risk_count || 0;
  const lowRiskCount = stats.low_risk_count || 0;
  const legitimateCount = stats.legitimate_count || 0;

  const pct = (value, total) => (total ? Number(((value / total) * 100).toFixed(2)) : 0);
  const changePct = (current, previous) => (previous ? Number((((current - previous) / previous) * 100).toFixed(2)) : 0);

  const generatedAtUtc = new Date().toISOString().replace('T', ' ').replace('Z', ' UTC').split('.')[0];
  const filtersApplied = metadata.filtersApplied || '';
  const generatedBy = metadata.generatedBy || 'admin';
  const timezone = metadata.timezone || Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';

  rows.push(['Metadata', 'Value']);
  rows.push(['Generated By', generatedBy]);
  rows.push(['Generated At (UTC)', generatedAtUtc]);
  rows.push(['Timezone', timezone]);
  rows.push(['Filters Applied', filtersApplied]);
  rows.push([]);

  rows.push(['Summary Metric', 'Value']);
  rows.push(['Period', stats.period || 'all_time']);
  rows.push(['Start Date', formatDateOnly(stats.start_date)]);
  rows.push(['End Date', formatDateOnly(stats.end_date)]);
  rows.push(['Calculated At (UTC)', formatDateTime(stats.calculated_at || new Date().toISOString())]);
  rows.push(['Total Analyses', totalCount]);
  rows.push(['Previous Total Analyses', previousTotalCount]);
  rows.push(['Total Analyses Change (%)', changePct(totalCount, previousTotalCount)]);
  rows.push(['Scams Detected', scamCount]);
  rows.push(['Previous Scams Detected', previousScamCount]);
  rows.push(['Scam Detection Change (%)', changePct(scamCount, previousScamCount)]);
  rows.push(['Scam Detection Rate (%)', Number((stats.scam_rate_percent || 0).toFixed(2))]);
  rows.push(['High Risk Count', highRiskCount]);
  rows.push(['High Risk Rate (%)', pct(highRiskCount, totalCount)]);
  rows.push(['Medium Risk Count', mediumRiskCount]);
  rows.push(['Medium Risk Rate (%)', pct(mediumRiskCount, totalCount)]);
  rows.push(['Low Risk Count', lowRiskCount]);
  rows.push(['Low Risk Rate (%)', pct(lowRiskCount, totalCount)]);
  rows.push(['Legitimate Count', legitimateCount]);
  rows.push(['Legitimate Rate (%)', pct(legitimateCount, totalCount)]);
  rows.push(['Top Scam Category', stats.top_scam_category || 'N/A']);

  rows.push([]);
  rows.push(['Confidence Distribution', 'Bucket', 'Count', 'Share (%)']);
  (stats.confidence_distribution || []).forEach((bucket) => {
    rows.push([
      'Confidence',
      bucket.bucket || '',
      bucket.count || 0,
      Number((bucket.percentage || 0).toFixed(2)),
    ]);
  });

  rows.push([]);
  rows.push(['Top Scam Categories', 'Rank', 'Category', 'Detections', 'Share (%)', 'Severity']);
  (categories || []).forEach((category, idx) => {
    rows.push([
      'Category',
      idx + 1,
      category.category || 'Unknown',
      category.count || 0,
      Number((category.percentage || 0).toFixed(2)),
      category.severity || 'unknown',
    ]);
  });

  rows.push([]);
  rows.push(['Daily Activity', 'Date', 'Total', 'Scams', 'Legitimate', 'Detection Rate (%)']);
  (stats.daily_counts || []).forEach((day) => {
    const total = day.total || 0;
    const scams = day.scams || 0;
    rows.push([
      'Day',
      formatDateOnly(day.date),
      total,
      scams,
      day.legitimate || 0,
      pct(scams, total),
    ]);
  });

  rows.push([]);
  rows.push(['Previous Period Daily Activity', 'Date', 'Total', 'Scams', 'Legitimate', 'Detection Rate (%)']);
  (stats.previous_daily_counts || []).forEach((day) => {
    const total = day.total || 0;
    const scams = day.scams || 0;
    rows.push([
      'Previous Day',
      formatDateOnly(day.date),
      total,
      scams,
      day.legitimate || 0,
      pct(scams, total),
    ]);
  });

  return rows
    .map((row) => row.map((value) => {
      const cell = value == null ? '' : String(value);
      if (cell.includes(',') || cell.includes('"') || cell.includes('\n')) {
        return `"${cell.replace(/"/g, '""')}"`;
      }
      return cell;
    }).join(','))
    .join('\n');
}

